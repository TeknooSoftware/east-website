declare(strict_types=1);

namespace Teknoo\East\Website\Tools\Tui\Screen;

use Symfony\Component\Tui\Widget\AbstractWidget;
use Symfony\Component\Tui\Widget\FocusableInterface;

/**
 * A screen of the interactive mode: a focusable widget between a title and its key hints.
 *
 * @copyright   Copyright (c) EIRL Richard Déloge (https://deloge.io - richard@deloge.io)
 * @copyright   Copyright (c) SASU Teknoo Software (https://teknoo.software - contact@teknoo.software)
 * @license     http://teknoo.software/license/bsd-3         3-Clause BSD License
 * @author      Richard Déloge <richard@teknoo.software>
 */
interface ScreenInterface
{
    public function title(): string;

    public function hints(): string;

    public function widget(): AbstractWidget&FocusableInterface;

    /**
     * Called when the screen opened by this one is closed, with its result (null when it was cancelled).
     */
    public function resume(mixed $result): void;
}
